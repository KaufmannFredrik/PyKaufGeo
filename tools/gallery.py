"""Build docs/GALLERY.md: what every finished milestone looks like.

Usage:  python tools/gallery.py            render the demo screenshots, then write GALLERY.md
        python tools/gallery.py --no-shots  only rewrite GALLERY.md

For each milestone marked done in PLAN.md (newest first) the page shows the demo
opened with ``python -m pykaufgeo --demo mN`` (rendered here to
``docs/screenshots/demo_mN.png``) and the design review screenshots of that
milestone (``docs/screenshots/mN_*.png``, made by tools/screenshot.py).
Run it after each milestone; tests/test_demos.py fails while the page is stale.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pykaufgeo.demos import DEMOS  # noqa: E402

TARGET = ROOT / "docs" / "GALLERY.md"
SHOTS = ROOT / "docs" / "screenshots"
THUMB_WIDTH = 280
PER_ROW = 3
ROW = re.compile(r"^\| (M\d+) \| (.+?) \| (.+?) \|$")


def milestones(plan: Path = ROOT / "PLAN.md") -> list[tuple[str, str, bool]]:
    """(key, scope, done) for each row of the milestone table in PLAN.md."""
    out = []
    for line in plan.read_text(encoding="utf-8").splitlines():
        m = ROW.match(line.strip())
        if m:
            out.append((m.group(1).lower(), m.group(2), m.group(3).strip() == "done"))
    return out


def _thumbs(files: list[Path]) -> list[str]:
    lines = ["<table>"]
    for i in range(0, len(files), PER_ROW):
        cells = "".join(
            f'<td><a href="screenshots/{f.name}"><img src="screenshots/{f.name}" width="{THUMB_WIDTH}"></a>'
            f"<br><code>{f.stem}</code></td>" for f in files[i:i + PER_ROW])
        lines.append(f"<tr>{cells}</tr>")
    lines.append("</table>")
    return lines


def gallery_markdown(shots: Path = SHOTS, plan: Path = ROOT / "PLAN.md") -> str:
    out = [
        "# PyKaufGeo gallery",
        "",
        "What each finished milestone looks like, newest first. Generated by `python tools/gallery.py`",
        "from PLAN.md, the milestone demos (`pykaufgeo/demos.py`) and the design review screenshots.",
        "",
        "Open a demo yourself:",
        "",
        "```",
        "python -m pykaufgeo --demo        # the newest milestone",
        "python -m pykaufgeo --demo m2     # a given milestone",
        "dist/PyKaufGeo.exe --demo         # the built program (python build.py)",
        "```",
        "",
        "or use Help > Milestone Demos in the app. Demos open unsaved; nothing is overwritten.",
    ]
    for key, scope, done in reversed(milestones(plan)):
        if not done:
            continue
        out += ["", f"## {key.upper()}: {scope}", ""]
        demo = DEMOS.get(key)
        hero = shots / f"demo_{key}.png"
        if demo is not None:
            out += [f"**Try it:** `python -m pykaufgeo --demo {key}`. {demo.hint}", ""]
        if hero.exists():
            out += [f"![{key.upper()} demo](screenshots/{hero.name})", ""]
        review = sorted(p for p in shots.glob(f"{key}_*.png"))
        if review:
            out += ["<details>", f"<summary>Design review screenshots ({len(review)})</summary>", ""]
            out += _thumbs(review)
            out += ["", "</details>"]
    return "\n".join(out) + "\n"


def render_demo_shots() -> list[Path]:
    """Open every demo in a headless window and save docs/screenshots/demo_<key>.png."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from screenshot import make_window, settle  # noqa: E402 (sets the offscreen platform)

    paths = []
    for key in DEMOS:
        app, win = make_window()
        win.open_demo(key)
        settle(app, 6)
        path = SHOTS / f"demo_{key}.png"
        win.grab().save(str(path))
        win.document.modified = False
        win.close()
        paths.append(path)
    return paths


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--no-shots", action="store_true", help="only rewrite GALLERY.md")
    args = parser.parse_args()
    SHOTS.mkdir(parents=True, exist_ok=True)
    if not args.no_shots:
        for path in render_demo_shots():
            print(path)
    TARGET.write_text(gallery_markdown(), encoding="utf-8", newline="\n")
    print(TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main())
